# Regular Expressions / Регулярные выражения

# Подключение модуля и основные функции
from re import *

data = 'кот кит кат кут'
pattern = 'к[ои]т'

print(*finditer(pattern,data))

# Метосимволы
# \d - любая цифра от 0 до 9
# \D - любая не цифра
# \s - любой пробельный символ
# \S - любой не пробельный символ
# \w - любая цифра, буква или _
# . - любой один символ

# [0-9] - любая цифра от 0 до 9
# [a-z] - любая буква латинского алфавита
# [0-9a-z] - любая цифра от 0 до 9 и буквы латинского алфавита
# [а-яё] - любая буква кирилицы
# ^ - исключающий символ
# [^0-9] - любой символ, но не цифра

# \n - переход на новую строку
# r''- создаёт сырую строку
# \t - создаёт табуляцию

# Квантификаторы
# Количество символов можно указывать в виде диапазона «{m, n}», что будет значить от m до n повторений предыдущего символа включительно
# * - {0,}
# + - {1,} (чтобы использовать + как символ, нужно использовать \+)
# ? - {0,1}

