# Методы обработки списков

data = [8, 5, 9, 2]

# Сортирует элементы списка в порядке возрастания (сохраняет изменения сразу в переменную)
data.sort()

# Сортирует элементы списка в порядке убывания (сохраняет изменения сразу в переменную)
data.sort(reverse=True)

# Сортирует элементы списка в порядке возрастания (отдельно нужно сохранить в переменную)
data = sorted(data)

print(data)


